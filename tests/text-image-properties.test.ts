test("standalone text has one atomic transaction and explicit fixed vs natural height without losing text",()=>{
  const e=new EditorSession(demo);
  const draft=createText({x:0,y:0});
  assert(saveText(e,e.generation,draft,"中文\nMixed text\n末行"));
  let original=e.doc.objects[draft.id];assert(original.kind==="text");
  assert.equal(original.heightMode,undefined);
  assert(!setTextStyle(e,original,{fontSize:20,color:"#663399",align:"right",width:85,heightMode:"fixed",height:0}));
  assert(setTextStyle(e,original,{x:25,y:-17,rotation:Math.PI/3,align:"right",fontSize:20,color:"#663399",width:85,height:28,heightMode:"fixed"}));
  const box=e.doc.objects[draft.id];assert(box.kind==="text");
  assert.deepEqual([box.at.x,box.at.y,box.rotation,box.width,box.height,box.fontSize,box.color,box.align],[25,-17,Math.PI/3,85,28,20,"#663399","right"]);
  const block=buildScene(e.doc).find(g=>g.id===box.id)?.items[0];
  assert(block?.kind==="textBlock"&&block.clip===true&&block.lines.length>=3);
  const decoded=decodeProject(encodeProject(e.doc,new AssetVault())).document;
  assert.deepEqual(decoded.objects[box.id],box);
  e.undo();assert.deepEqual(e.doc.objects[box.id],original);
  e.redo();
  const fixed=e.doc.objects[box.id];assert(fixed.kind==="text");
  assert(saveText(e,e.generation,fixed,"全部文本\n第二行\n第三行"));
  const edited=e.doc.objects[box.id];assert(edited.kind==="text");
  assert.equal(edited.height,28);assert.equal(edited.text,"全部文本\n第二行\n第三行");
  assert(setTextStyle(e,edited,{width:edited.width,align:edited.align,fontSize:edited.fontSize,color:edited.color,heightMode:"fit"}));
  const fit=e.doc.objects[box.id];assert(fit.kind==="text");
  assert.equal(fit.heightMode,undefined);assert(fit.height>28);
  const malformed={...e.doc,objects:{...e.doc.objects,[box.id]:{...fit,heightMode:"hidden"}}};
  assert(validateDocument(malformed).length>0);
});

test("image rotation and unlocked aspect survive save and undo; restore ratio uses original asset",()=>{
  const e=new EditorSession(demo);
  const vault=new AssetVault();
  const asset=vault.add({bytes:Uint8Array.from(Buffer.from(png,"base64")),meta:{id:"test-original",mime:"image/png",pixelWidth:8,pixelHeight:5}});
  const image:ImageObject={id:"precise-image",kind:"image",assetId:asset.id,at:{x:0,y:0},width:80,height:50,rotation:0};
  assert(e.commitEdit({label:"import",patches:[{op:"putAsset",value:asset},{op:"putObject",value:image}]},e.generation,[image.id]));
  assert(e.transformSelection({x:12,y:24,width:100,height:110,lockRatio:false,imageRotation:Math.PI/6}));
  const unlocked=e.doc.objects[image.id];assert(unlocked.kind==="image");
  assert.deepEqual([unlocked.width,unlocked.height,unlocked.rotation,unlocked.lockAspect],[100,110,Math.PI/6,false]);
  assert.deepEqual(decodeProject(encodeProject(e.doc,vault)).document.objects[image.id],unlocked);
  e.undo();const original=e.doc.objects[image.id];assert(original.kind==="image");
  assert.equal(original.lockAspect,undefined);assert.equal(original.width,80);
  e.redo();
  assert(e.transformSelection({x:12,y:24,width:100,height:50,imageNaturalRatio:true,ratioDriver:"height",lockRatio:true}));
  const restored=e.doc.objects[image.id];assert(restored.kind==="image");
  assert.equal(restored.width,80);assert.equal(restored.height,50);assert.equal(restored.lockAspect,undefined);
  assert(e.transformSelection({x:12,y:24,width:80,height:75,ratioDriver:"height"}));
  const locked=e.doc.objects[image.id];assert(locked.kind==="image");
  assert.equal(locked.width,120);
});
